"""Check every careers board in a YAML file and write only the reachable ones to data/companies.yaml.

Usage:  python -m scripts.validate_boards [input.yaml]
"""

import asyncio
import sys
from pathlib import Path

import httpx
import yaml

from app.config import DATA_DIR
from app.scrapers.ats import probe_board


async def main(src: Path) -> None:
    boards = yaml.safe_load(src.read_text(encoding="utf-8"))
    sem = asyncio.Semaphore(10)
    valid: dict[str, list] = {}

    async def check(client, kind, b):
        async with sem:
            try:
                n = await probe_board(client, kind, b)
                print(f"  ok   {kind:16} {b['name']:28} {n} jobs")
                valid.setdefault(kind, []).append(b)
            except Exception as e:
                print(f"  FAIL {kind:16} {b['name']:28} {str(e)[:60]}")

    async with httpx.AsyncClient(timeout=25, follow_redirects=True) as client:
        await asyncio.gather(*(check(client, k, b) for k, lst in boards.items() for b in lst))

    seen = set()
    out: dict[str, list] = {}
    for kind in boards:  # keep original order, drop duplicate companies
        for b in boards[kind]:
            if b in valid.get(kind, []) and b["name"] not in seen:
                seen.add(b["name"])
                out.setdefault(kind, []).append(b)
    dest = DATA_DIR / "companies.yaml"
    header = "# Careers boards scraped daily. Generated by scripts/validate_boards.py; edit freely.\n"
    dest.write_text(header + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=200), encoding="utf-8")
    print(f"\n{sum(len(v) for v in out.values())} boards written to {dest}")


if __name__ == "__main__":
    asyncio.run(main(Path(sys.argv[1]) if len(sys.argv) > 1 else DATA_DIR / "companies.candidates.yaml"))
